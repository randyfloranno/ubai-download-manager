//! `cargo xtask licences`: write `target/licences/THIRD-PARTY.md` with every third-party
//! crate (name, version, licence, repository) and the licence texts shipped with it.

use std::fmt::Write as _;
use std::path::Path;

use crate::{metadata, util};

fn is_licence_file(name: &str) -> bool {
    let up = name.to_ascii_uppercase();
    ["LICENSE", "LICENCE", "COPYING", "NOTICE"]
        .iter()
        .any(|p| up.starts_with(p))
}

pub fn run() -> Result<(), String> {
    let meta = metadata::load(false)?;
    let mut pkgs: Vec<&metadata::Package> = meta
        .packages
        .iter()
        .filter(|p| !meta.workspace_members.contains(&p.id))
        .collect();
    pkgs.sort_by(|a, b| (&a.name, &a.version).cmp(&(&b.name, &b.version)));

    let mut doc = String::new();
    doc.push_str(
        "# Third-party licences\n\nGenerated by `cargo xtask licences` from `cargo metadata`.\n\n",
    );
    doc.push_str("| Crate | Version | Licence | Repository |\n|---|---|---|---|\n");
    for p in &pkgs {
        let _ = writeln!(
            doc,
            "| {} | {} | {} | {} |",
            p.name,
            p.version,
            p.license.as_deref().unwrap_or("(see licence file)"),
            p.repository.as_deref().unwrap_or("")
        );
    }
    doc.push_str("\n---\n\n## Licence texts\n");
    let mut files_found = 0usize;
    for p in &pkgs {
        let Some(dir) = Path::new(&p.manifest_path).parent() else {
            continue;
        };
        let Ok(rd) = std::fs::read_dir(dir) else {
            continue;
        };
        let mut files: Vec<_> = rd
            .flatten()
            .filter(|e| e.file_type().is_ok_and(|t| t.is_file()))
            .filter(|e| is_licence_file(&e.file_name().to_string_lossy()))
            .map(|e| e.path())
            .collect();
        files.sort();
        if files.is_empty() {
            continue;
        }
        let _ = writeln!(doc, "\n### {} {}\n", p.name, p.version);
        for f in files {
            let Ok(text) = std::fs::read_to_string(&f) else {
                continue;
            };
            files_found += 1;
            let fname = f
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_default();
            let _ = writeln!(doc, "#### {fname}\n\n```text\n{}\n```", text.trim_end());
        }
    }
    let out_dir = util::root().join("target").join("licences");
    std::fs::create_dir_all(&out_dir)
        .map_err(|e| format!("cannot create {}: {e}", util::rel(&out_dir)))?;
    let out = out_dir.join("THIRD-PARTY.md");
    std::fs::write(&out, doc).map_err(|e| format!("cannot write {}: {e}", util::rel(&out)))?;
    println!(
        "licences: wrote {} ({} crates, {} licence files)",
        util::rel(&out),
        pkgs.len(),
        files_found
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn licence_file_names() {
        for n in [
            "LICENSE",
            "LICENSE-MIT",
            "license-apache",
            "COPYING",
            "NOTICE.txt",
            "LICENCE",
        ] {
            assert!(is_licence_file(n), "{n}");
        }
        for n in ["README.md", "Cargo.toml", "src"] {
            assert!(!is_licence_file(n), "{n}");
        }
    }
}
